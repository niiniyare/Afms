"""
Shift Correction applier: Native document (FMS-G02).

Cancels and amends one ERPNext document (Sales Invoice, Payment Entry,
Journal Entry) that was generated by the shift. Nothing in the shift's
own data changes — only the native document is affected.
"""

from __future__ import annotations

import frappe
from frappe import _


def apply(correction) -> None:
	"""
	For each item in correction.items (target_type == 'Document'):
	  1. Load the target document.
	  2. Cancel it (frappe.flags.fms_correction is already True).
	  3. Amend it, apply the field change from the item, submit.
	  4. Record both names in correction.applied_documents.
	"""
	applied: list[str] = []

	for item in correction.items:
		if item.target_type != "Document":
			frappe.throw(
				_("Native document correction expects items with target_type 'Document', got '{0}'.").format(
					item.target_type
				)
			)

		if not item.target_doctype or not item.target_name:
			frappe.throw(_("Correction item row {0} is missing target DocType or name.").format(item.idx))

		target = frappe.get_doc(item.target_doctype, item.target_name)

		# Validate it belongs to this shift
		shift_on_doc = target.get("fms_forecourt_shift")
		if shift_on_doc and shift_on_doc != correction.forecourt_shift:
			frappe.throw(
				_("{0} {1} belongs to shift {2}, not {3}.").format(
					item.target_doctype,
					item.target_name,
					shift_on_doc,
					correction.forecourt_shift,
				)
			)

		# Cancel the original (fms_correction flag is already True from the controller)
		target.cancel()
		applied.append(f"Cancelled: {item.target_doctype} {item.target_name}")

		# Amend and apply the field change
		amended = frappe.copy_doc(target)
		amended.amended_from = target.name
		amended.docstatus = 0

		if item.field and item.new_value is not None:
			amended.set(item.field, item.new_value)

		amended.flags.ignore_permissions = True
		amended.insert()
		amended.submit()
		applied.append(f"Amended: {item.target_doctype} {amended.name}")

	correction.db_set(
		"applied_documents",
		"\n".join(applied) if applied else "",
		update_modified=False,
	)
